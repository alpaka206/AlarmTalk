/**
 * 운세(사주) 입력 계약 — **세 구현의 단일 출처**.
 *
 * ⚠ 이 파일이 왜 생겼나: 태어난 시간의 형식이 세 곳에서 서로 달랐다.
 *  - 안드로이드: 사주 시진 13종을 **구간 문자열**로 보낸다(`"00:00~01:30"`)
 *  - iOS: 대략 시간대 4종
 *  - 서버: `HH:MM` 만 통과시키는 정규식
 *
 * 결과로 **안드로이드의 모든 선택지가 400 으로 거절됐다.** 게다가 `PATCH /user/me` 는
 * 운세와 날씨를 한 payload 로 받으므로, 태어난 시간을 고른 순간 **날씨 지역까지 함께
 * 저장에 실패**했다. 실패는 조용히 삼켜져 사용자는 저장된 줄 알고 화면을 떠났다.
 *
 * 어느 쪽이 맞나: **구간이 맞다.** 사주는 두 시간짜리 시진 단위로 보는 것이고,
 * 안드로이드 주석도 "저장값이 곧 백엔드 프롬프트로 전달되므로 로케일 번역 없이 숫자
 * 구간 문자열을 쓴다" 고 적어 두었다. 서버의 프롬프트 경로(`vertex-translate.ts`)도
 * 자유 문자열을 그대로 다룬다 — 낡은 건 검증 정규식 하나뿐이었다.
 */

/**
 * 태어난 시간 선택지. **사주 시진 경계(한국 표준시 +30분 보정)** 그대로다.
 *
 * ⚠ 값을 번역하지 말 것. 이 문자열이 그대로 저장되고 프롬프트로 들어간다 —
 * 기기 언어에 따라 값이 달라지면 같은 사람이 기기마다 다른 사주를 갖게 된다.
 * 화면에 다른 말로 보여주고 싶으면 **표시만** 바꾸고 저장값은 이 목록을 쓴다.
 */
export const FORTUNE_BIRTH_TIME_CHOICES = [
  '00:00~01:30',
  '01:31~03:30',
  '03:31~05:30',
  '05:31~07:30',
  '07:31~09:30',
  '09:31~11:30',
  '11:31~13:30',
  '13:31~15:30',
  '15:31~17:30',
  '17:31~19:30',
  '19:31~21:30',
  '21:31~23:30',
  '23:31~24:00',
] as const;

/**
 * "태어난 시간을 모른다" 는 **정당한 답**이다 — 실제로 모르는 사람이 많다.
 * 빈 값과 구분해야 한다: 빈 값은 '아직 안 골랐다', 이건 '골랐는데 모른다' 다.
 */
export const FORTUNE_BIRTH_TIME_UNKNOWN = '시간 모름';

/** `HH:MM` 한 시각. 옛 클라이언트가 보낸 값과 사용자가 직접 친 값을 위해 남긴다. */
const EXACT_TIME_RE = /^([01]\d|2[0-3]):[0-5]\d$/;

/** `HH:MM~HH:MM` 구간. 끝값 `24:00` 을 허용한다(마지막 시진이 그렇게 끝난다). */
const RANGE_RE = /^([01]\d|2[0-3]):[0-5]\d~(([01]\d|2[0-3]):[0-5]\d|24:00)$/;

/**
 * 저장해도 되는 태어난 시간인가.
 *
 * ⚠ **목록 대조만 하지 말 것.** 시진 경계를 나중에 손보면 옛 값을 가진 기존 사용자가
 * 전부 400 을 맞는다(그게 이 파일이 생긴 원인이다). 형식이 맞으면 받아들이고,
 * 목록은 **고르는 화면의 선택지**로만 쓴다.
 */
export function isValidFortuneBirthTime(value: string): boolean {
  if (value === FORTUNE_BIRTH_TIME_UNKNOWN) return true;
  return EXACT_TIME_RE.test(value) || RANGE_RE.test(value);
}

/** 생년월일은 `YYYY-MM-DD` 하나뿐이다 — 세 구현 모두 같다. */
export const FORTUNE_BIRTH_DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

export function isValidFortuneBirthDate(value: string): boolean {
  return FORTUNE_BIRTH_DATE_RE.test(value);
}
