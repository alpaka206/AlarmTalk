import Foundation

/// **유료 게이트 문구의 유일한 출처.**
///
/// "이 기능은 유료여야 한다" 고 말하는 자리는 여러 곳이지만 **문장은 하나**다
/// (2026-08-11 지시). 화면마다 다른 문장을 쓰면 같은 사실을 서너 가지로 말하게 되고,
/// 하나를 고칠 때 나머지가 남는다.
///
/// 안드로이드의 짝은 `res/values/strings.xml` 의 `plan_gate_paid_message` 다 —
/// **한쪽만 고치지 말 것.**
///
/// ⚠ **여기에 로그인 게이트·기본목소리 게이트를 섞지 말 것.**
/// - 로그인 게이트("로그인이 필요해요")는 **돈 문제가 아니다.** 이 문장을 쓰면 로그인만
///   하면 되는 사람에게 돈을 내라고 하게 된다.
/// - 기본(시스템) 목소리로 직접 입력이 막히는 것은 **유료여도 막힌다.** 이 문장을 쓰면
///   이미 이용권을 산 사람에게 "유료 이용권에서 쓸 수 있어요" 라고 말하는 셈이다.
///
/// ⚠ **게이트가 아닌 모달에도 쓰지 말 것** — 월 등록 한도 안내(이미 유료인데 이번 달을
/// 다 씀), 삭제 확인 같은 것은 다른 사실이다.
enum PaidGateCopy {
    /// 유료 게이트의 **설명** 문장. 제목은 자리마다 다를 수 있다.
    static let message = "해당 기능은 유료 이용권에서 사용할 수 있어요."

    /// 이용권 화면으로 보내는 액션 라벨.
    static let viewPlans = "이용권 보기"

    /// ⚠ **쿠폰 갈래는 유료 게이트에 **항상** 둔다**(2026-08-11 지시).
    /// 돈을 내는 것 말고 **코드로 여는 길**이 있는데, 그 길을 게이트마다 다르게 두면
    /// 어떤 화면에서는 있고 어떤 화면에서는 없다(실제로 iOS 목소리 게이트에는 없었다).
    static let redeemCode = "쿠폰이 있어요"
}
