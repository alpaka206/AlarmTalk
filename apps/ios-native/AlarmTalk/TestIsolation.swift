import Foundation

/// **유닛 테스트가 기기의 진짜 사용자 상태를 건드리지 못하게 가르는 한 곳.**
///
/// 유닛 테스트는 **호스트 앱 프로세스 안에서** 돈다. 그래서 테스트가 만든 객체가 잡는
/// 저장 위치는 기본값 그대로 두면 **사용자가 쓰는 바로 그 위치**다 — 키체인 서비스도,
/// App Group 의 음원 캐시 디렉터리도, Documents 의 알람 JSON 도 전부 같은 것을 가리킨다.
///
/// 2026-08-19 실기기에서 실제로 그 대가를 치렀다. 기기에서 테스트를 한 번 돌릴 때마다
/// 아래 셋이 함께 날아갔다:
///
/// - **로그인이 풀렸다** — `AuthViewModelTests` 가 진짜 `AuthViewModel.signOut()` 을 부르고,
///   그 안의 `KeychainStore.deleteSession()` 은 서비스 이름으로만 항목을 지운다. 테스트용
///   가짜 세션이 아니라 **기기에 저장된 진짜 세션**이 지워진다.
/// - **기본 목소리 클립이 사라졌다** — 그래서 다음 로그인이 스톡 클립을 다시 받았다.
///   "로그인할 때마다 목소리를 다시 받는다" 는 제보의 정체가 이것이었다(앱 버그가 아니라
///   내가 돌린 테스트였다).
/// - **알람 파일이 열렸다** — `LocalAlarmStore()` 를 기본 생성자로 만드는 테스트는 사용자의
///   `voice-alarm-ios-alarms.json` 을 그대로 잡는다.
///
/// 앱 데이터 컨테이너 자체는 멀쩡했다(8/10 파일이 그대로 있었다) — **재설치가 아니라
/// 테스트가 지운 것**이라는 증거이기도 하다.
///
/// ⚠ **새 저장소를 만들면 여기에 태운다.** 테스트마다 격리를 기억하게 하면 언젠가 잊고,
/// 잊은 대가는 개발자 기기의 로그인·알람·목소리다. 판정을 **저장소 쪽 한 곳**에 두는 이유다.
enum TestIsolation {

    /// XCTest 러너가 **호스트 앱 프로세스에** 넣어 주는 환경변수. 유닛 테스트 실행일 때만 있다.
    ///
    /// UI 테스트(`AlarmTalkUITests`)는 앱을 **별도 프로세스로** 띄우므로 여기에 걸리지
    /// 않는다 — 의도한 것이다. UI 테스트는 사용자가 쓰는 그대로의 앱을 검증해야 하고,
    /// 이미 `-UIPreviewSeed` 로 가짜 세션을 쓴다.
    static let isRunningUnitTests: Bool =
        ProcessInfo.processInfo.environment["XCTestConfigurationFilePath"] != nil

    /// 저장 위치·키체인 서비스 이름에 붙이는 꼬리표. 평상시에는 빈 문자열이라
    /// **출시 빌드의 경로가 달라지지 않는다.**
    static var storageSuffix: String { isRunningUnitTests ? "-xctest" : "" }
}
