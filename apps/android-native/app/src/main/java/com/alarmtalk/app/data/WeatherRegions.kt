        byKey(key)?.let { WeatherRegionLabels(it.legacyCountry, it.legacyCity) }

    /** 나라 표기("대한민국"·"Japan"·"アメリカ"·"US" …) → 나라. 모르는 표기면 null. */
    fun countryForLabel(label: String?): WeatherCountry? {
        val key = aliasKey(label)
        return if (key.isEmpty()) null else countryAliasIndex[key]
    }

    /**
     * 옛 (나라, 도시) 문자열 → 지역. 못 찾으면 null — 그 값은 서버의 옛 경로(엄격한 지오코딩)로
     * 계속 돌고, 화면은 다시 고르라고 권한다. 규칙은 `scripts/gen-weather-regions.py` 의
     * `resolve` 와 글자 하나까지 같다(서버 `WeatherRegions.resolveAlias` 도 같다).
     */
    fun resolveAlias(country: String?, city: String?): WeatherRegion? {
        val c = canonicalize(country)
        val t = canonicalize(city)
        if (c.isEmpty() && t.isEmpty()) return null
        val code = if (c.isEmpty()) null else countryForLabel(c)
        if (c.isEmpty() || code != null) {
            val first = if (' ' in t) t.substringBefore(' ') else ""
            val hit = byKey(match(t) ?: if (hasLatin(first)) null else match(first)) ?: return null
            // 일본·미국이라고 적었으면 그 나라 안에서만. 대한민국은 옛 앱이 자동으로 붙인 값이라 어긋나도 받는다.
            return if (code != null && code != WeatherCountry.KR && hit.country != code) null else hit
        }
        return byKey(match(canonicalize("$c $t")) ?: if (hasLatin(c)) null else match(c))
    }

    /** 로마자가 있는 낱말은 첫 낱말로 다시 찾지 않는다("Birmingham England" 가 앨라배마로 간다). */
    private fun hasLatin(text: String): Boolean = text.any { it in 'a'..'z' }

    /** NFKC → 소문자 → 구분 글자를 공백으로 → 공백 하나로·앞뒤 제거. */
    fun canonicalize(raw: String?): String {
        if (raw.isNullOrEmpty()) return ""
        val folded = Normalizer.normalize(raw, Normalizer.Form.NFKC).lowercase(Locale.ROOT)
        val spaced = buildString(folded.length) {
            for (ch in folded) append(if (SEPARATORS.indexOf(ch) >= 0) ' ' else ch)
        }
        return spaced.split(' ').filter { it.isNotEmpty() }.joinToString(" ")
    }

    /** 별칭 표의 열쇠 — [canonicalize] 에서 공백까지 뺀 것. */
    fun aliasKey(raw: String?): String = canonicalize(raw).replace(" ", "")

    private fun match(text: String): String? {
        if (text.isEmpty()) return null
        aliasIndex[aliasKey(text)]?.let { return it }
        val stripped = stripSuffix(text) ?: return null
        return aliasIndex[aliasKey(stripped)]
    }

    private fun stripSuffix(text: String): String? {
        for (suffix in SUFFIXES) {
            if (text.endsWith(suffix)) return text.dropLast(suffix.length).trim().ifEmpty { null }
        }
        return null
    }

