/**
 * 지역 목록의 나라. 공휴일 달력 국가([HolidayCountryPreferenceStore])도 같은 코드를 쓴다 —
 * 지역을 고르면 그 나라가 공휴일 국가가 된다.
 */
enum class WeatherCountry(
    val code: String,
    /** 옛 앱이 읽는 `country` 칸에 쓰는 글자. 언어와 무관하게 한국어다. */
    val legacyLabel: String,
    @StringRes val nameRes: Int,
) {
    KR("KR", "대한민국", R.string.weather_country_kr),
    JP("JP", "일본", R.string.weather_country_jp),
    US("US", "미국", R.string.weather_country_us),
    ;

    companion object {
        /** "KR"·"jp" 같은 코드 → 나라. 모르는 코드면 null. */
        fun fromCode(code: String?): WeatherCountry? {
            val wanted = code?.trim()?.uppercase(Locale.ROOT) ?: return null
            return entries.firstOrNull { it.code == wanted }
        }
    }
}

/**
 * 고를 수 있는 지역 하나. 저장·전송 값은 [key] 이고, 보이는 이름은 [nameRes] 다.
 * [seatNameRes] 는 날씨를 재는 대표 도시(경기 → 수원)가 지역 이름과 다를 때만 있다.
 */
data class WeatherRegion(
    val key: String,
    val country: WeatherCountry,
    /** 나라 안에서의 목록 순서(1부터). */
    val order: Int,
    @StringRes val nameRes: Int,
    @StringRes val seatNameRes: Int?,
    /** 옛 앱이 읽는 `city` 칸에 쓰는 글자(한국어 이름). */
    val legacyCity: String,
) {
    /** 옛 앱이 읽는 `country` 칸에 쓰는 글자. */
    val legacyCountry: String get() = country.legacyLabel
}

